import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import yaml from "js-yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

// Inspects the existing Dockerfile to produce a plugins.yaml that reproduces
// today's behavior. The mapping from npm package name to (tier, key) is driven
// by the registry itself — both the canonical package field AND the @rmdes
// fork name for entries marked `overridden: true` resolve to the same registry
// entry (since the npm overrides field swaps them at install time).

function buildPackageIndex(registry) {
  // Reverse index: npm package name -> { tier, key, entry }
  const index = new Map();
  for (const tier of ["core", "post_types", "syndicators", "endpoints"]) {
    for (const entry of registry[tier] || []) {
      index.set(entry.package, { tier, key: entry.key, entry });
      if (entry.overridden && entry.package.startsWith("@indiekit/")) {
        // Map the @rmdes fork name to the same registry key.
        // Heuristic: @indiekit/endpoint-share -> @rmdes/indiekit-endpoint-share
        //            @indiekit/frontend       -> @rmdes/indiekit-frontend
        const suffix = entry.package.slice("@indiekit/".length);
        const forkName = suffix.startsWith("indiekit-")
          ? `@rmdes/${suffix}`
          : `@rmdes/indiekit-${suffix}`;
        index.set(forkName, { tier, key: entry.key, entry });
      }
    }
  }
  return index;
}

function stripComments(text) {
  return text
    .split("\n")
    .map((line) => line.replace(/^\s*#.*$/, "").replace(/\s+#.*$/, ""))
    .join("\n");
}

async function migrate(siteName) {
  const registry = yaml.load(await readFile(path.join(ROOT, "plugin-registry/plugin-registry.yaml"), "utf8"));
  const dockerfile = await readFile(path.join(ROOT, "Dockerfile"), "utf8");

  const installMatch = dockerfile.match(/npm install[\s\S]*?\n\n/);
  if (!installMatch) throw new Error("Could not find npm install block in Dockerfile");
  const installBlock = stripComments(installMatch[0]);
  const packages = [...new Set(installBlock.match(/@[a-z0-9-]+\/[a-z0-9-]+/g) || [])];

  const packageIndex = buildPackageIndex(registry);
  const manifest = { post_types: {}, syndicators: {}, endpoints: {} };
  const unknown = [];

  for (const pkg of packages) {
    const hit = packageIndex.get(pkg);
    if (!hit) {
      unknown.push(pkg);
      continue;
    }
    // Core plugins are never expressed in the manifest — they're implicit
    if (hit.tier === "core") continue;
    // Indiekit itself is not a plugin
    if (pkg === "@indiekit/indiekit") continue;
    // Skip plugins that are already default_enabled — manifest only encodes overrides
    if (hit.entry.default_enabled === true) continue;
    manifest[hit.tier][hit.key] = { enabled: true };
  }

  if (unknown.length > 0) {
    console.warn(`Packages in Dockerfile not in registry (skipped):`);
    for (const u of unknown) console.warn(`  ${u}`);
  }

  const outPath = path.join(ROOT, "sites", siteName, "config/plugins.yaml");
  await mkdir(path.dirname(outPath), { recursive: true });
  const header = `# sites/${siteName}/config/plugins.yaml
# Generated by scripts/manifest-from-current.mjs from the current Dockerfile.
# Only entries that differ from registry defaults are present (core is implicit).
#
# Edit this file (or use \`make plugin-edit\`) to enable/disable plugins for ${siteName}.
`;
  await writeFile(outPath, header + yaml.dump(manifest, { indent: 2 }));
  console.log(`Wrote ${outPath}`);
  console.log(`Overrides: ${Object.keys(manifest.post_types).length} post_types + ${Object.keys(manifest.syndicators).length} syndicators + ${Object.keys(manifest.endpoints).length} endpoints`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const site = process.env.SITE || process.argv[2];
  if (!site) { console.error("Usage: SITE=foo node manifest-from-current.mjs"); process.exit(1); }
  await migrate(site);
}
